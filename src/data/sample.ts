type Annotation = {
  anchor: string
  format: 'highlight' | 'comment'
  sourceRange: [number, number]
}

function writeBack(source: string, note: Annotation) {
  return source.slice(0, note.sourceRange[0])
    + note.anchor
    + source.slice(note.sourceRange[1])
}
